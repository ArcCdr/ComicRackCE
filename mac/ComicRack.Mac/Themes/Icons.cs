using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using Avalonia;
using Avalonia.Controls;
using Avalonia.Media;
using Avalonia.Media.Imaging;
using Avalonia.Platform;
using Avalonia.Styling;
using SkiaSharp;

namespace ComicRack.Mac.Themes
{
	/// <summary>
	/// The images of the WinForms original by the name the original uses (<c>Resources.FitWidth</c> is <c>Icons.Get("FitWidth")</c>),
	/// chrome-guidelines section 5. The files stay where they are in the repository: <c>ComicRack.Mac.csproj</c> links them into the
	/// assembly (<c>Assets/Original/&lt;repository path&gt;</c>) and <c>Assets/icon-map.json</c> (generated by
	/// <c>mac/tools/icon-map/icon-map.py</c> from the four <c>Properties/Resources.resx</c> files) tells which file a name is.
	/// <list type="bullet">
	/// <item>Dark appearance: a name that has a dark variant (<c>Resources/Dark/&lt;name&gt;.png</c>, found by the original's rule in
	/// <c>ResourceManagerEx</c>) gives the dark image while the application shows the dark theme, else the light image.</item>
	/// <item>Magenta (#FF00FF) is the transparent colour of the original's toolbar images; GIF and BMP sources get it keyed out, PNG
	/// sources are left as they are.</item>
	/// <item>There are no high-DPI variants. A 16 pixel image is 16 device independent units wide and Retina scales it by two with
	/// high-quality filtering, as the original does on a 200 % Windows display (<see cref="CreateImage"/>).</item>
	/// </list>
	/// A name that exists in more than one project (<c>GoLast</c> is in the main app and in the reader project) resolves to the first
	/// project of <see cref="ProjectOrder"/>; <c>"ComicRack.Engine.Display.Forms:GoLast"</c> names the project.
	/// </summary>
	public static class Icons
	{
		private const string MapUri = "avares://ComicRack.Mac/Assets/icon-map.json";
		private const string FilesUri = "avares://ComicRack.Mac/Assets/Original/";

		// PublicationOnly: a load that fails (no Avalonia services yet) is not remembered; the next use tries again. The default mode would raise the same exception for ever.
		private static readonly Lazy<IconMap> map = new Lazy<IconMap>(LoadMap, System.Threading.LazyThreadSafetyMode.PublicationOnly);
		private static readonly ConcurrentDictionary<string, Bitmap> cache = new ConcurrentDictionary<string, Bitmap>();
		private static readonly ConcurrentDictionary<string, Bitmap> pictures = new ConcurrentDictionary<string, Bitmap>(StringComparer.Ordinal);

		/// <summary>The projects in lookup order (the main app first).</summary>
		public static IReadOnlyList<string> ProjectOrder => map.Value.Order;

		/// <summary>Every name that <see cref="Get"/> accepts without a project (the first project wins), sorted.</summary>
		public static IReadOnlyList<string> Names => map.Value.AllNames;

		/// <summary>The names of one project as the project's resx lists them.</summary>
		public static IReadOnlyCollection<string> NamesOf(string project) => map.Value.Projects[project].Keys;

		/// <summary>True if the name (optionally <c>Project:Name</c>) is a resource of the original.</summary>
		public static bool Contains(string name) => map.Value.Find(name) != null;

		/// <summary>True if the name has a dark variant.</summary>
		public static bool HasDark(string name) => map.Value.Find(name)?.Dark != null;

		/// <summary>The repository path of the file a name is (light image).</summary>
		public static string PathOf(string name) => (map.Value.Find(name) ?? throw Unknown(name)).Path;

		/// <summary>The image of a name for the appearance (<see cref="ThemeTokens.Current"/> if null); the cached bitmap is shared, do not dispose it.</summary>
		public static Bitmap Get(string name, ThemeVariant variant = null)
		{
			Bitmap bitmap = TryGet(name, variant);
			if (bitmap == null)
			{
				throw Unknown(name);
			}
			return bitmap;
		}

		/// <summary>
		/// Gives a picture that is not a resource of the original (the image of a script command, P4.5) a name that <see cref="TryGet"/>, <c>CrIcon</c> and <c>CrToolButton.IconName</c>
		/// accept, so that views name pictures and never load them. The file is decoded as the original's toolbar images are (GIF and BMP get magenta keyed out). A name is
		/// replaced by a second registration; the name must not be a name of the original. Returns false (and registers nothing) when the file cannot be decoded.
		/// </summary>
		public static bool RegisterFile(string name, string file)
		{
			if (string.IsNullOrEmpty(name) || map.Value.Find(name) != null)
			{
				throw new ArgumentException("The name is empty or a resource of the original: " + name, nameof(name));
			}
			try
			{
				string extension = Path.GetExtension(file) ?? string.Empty;
				using (FileStream stream = File.OpenRead(file))
				{
					pictures[name] = Decode(stream, extension.Equals(".gif", StringComparison.OrdinalIgnoreCase) || extension.Equals(".bmp", StringComparison.OrdinalIgnoreCase));
				}
				return true;
			}
			catch (Exception)
			{
				return false;
			}
		}

		/// <summary>Takes a picture registered by <see cref="RegisterFile"/> out again.</summary>
		public static void Unregister(string name) => pictures.TryRemove(name ?? string.Empty, out _);

		/// <summary>Like <see cref="Get"/>, null for a name that is not a resource of the original.</summary>
		public static Bitmap TryGet(string name, ThemeVariant variant = null)
		{
			if (name != null && pictures.TryGetValue(name, out Bitmap registered))
			{
				return registered;
			}
			IconEntry entry = map.Value.Find(name);
			if (entry == null)
			{
				return null;
			}
			string path = (variant ?? ThemeTokens.Current) == ThemeVariant.Dark && entry.Dark != null ? entry.Dark : entry.Path;
			return cache.GetOrAdd(path, Load);
		}

		/// <summary>
		/// An <see cref="Image"/> that shows the picture at its own size in device independent units (16 pixels = 16 units) with
		/// high-quality filtering, which is what scales it on a Retina display.
		/// </summary>
		public static Image CreateImage(string name, ThemeVariant variant = null)
		{
			Bitmap bitmap = Get(name, variant);
			var image = new Image { Source = bitmap, Width = bitmap.Size.Width, Height = bitmap.Size.Height, Stretch = Stretch.Fill };
			RenderOptions.SetBitmapInterpolationMode(image, BitmapInterpolationMode.HighQuality);
			return image;
		}

		/// <summary>
		/// Decodes an image of the original. With <paramref name="keyMagenta"/> every opaque #FF00FF pixel becomes transparent (the
		/// original's <c>ImageTransparentColor</c>); the result is a premultiplied BGRA bitmap at 96 dpi.
		/// </summary>
		public static Bitmap Decode(Stream stream, bool keyMagenta)
		{
			if (!keyMagenta)
			{
				return new Bitmap(stream);
			}
			using (SKBitmap decoded = SKBitmap.Decode(stream) ?? throw new InvalidDataException("The image cannot be decoded."))
			using (SKBitmap bgra = new SKBitmap(new SKImageInfo(decoded.Width, decoded.Height, SKColorType.Bgra8888, SKAlphaType.Premul)))
			{
				if (!decoded.CopyTo(bgra, SKColorType.Bgra8888))
				{
					throw new InvalidDataException("The image cannot be converted to BGRA.");
				}
				var pixels = new byte[bgra.Width * bgra.Height * 4];
				System.Runtime.InteropServices.Marshal.Copy(bgra.GetPixels(), pixels, 0, pixels.Length);
				KeyMagenta(pixels);
				var result = new WriteableBitmap(new PixelSize(bgra.Width, bgra.Height), new Vector(96, 96), PixelFormat.Bgra8888, AlphaFormat.Premul);
				using (ILockedFramebuffer buffer = result.Lock())
				{
					int rowBytes = bgra.Width * 4;
					for (int y = 0; y < bgra.Height; y++)
					{
						System.Runtime.InteropServices.Marshal.Copy(pixels, y * rowBytes, buffer.Address + y * buffer.RowBytes, rowBytes);
					}
				}
				return result;
			}
		}

		private static readonly System.Runtime.CompilerServices.ConditionalWeakTable<Bitmap, Bitmap> monochrome = new System.Runtime.CompilerServices.ConditionalWeakTable<Bitmap, Bitmap>();

		/// <summary>
		/// The picture without its colours: every pixel becomes the grey of its luminance (alpha kept), the look of the Native variant of
		/// <see cref="ChromeElement.Icons"/>. One copy per picture, kept as long as the picture lives (never dispose it). The picture itself is not changed.
		/// </summary>
		public static Bitmap Monochrome(Bitmap bitmap)
		{
			if (bitmap == null)
			{
				return null;
			}
			lock (monochrome)
			{
				if (monochrome.TryGetValue(bitmap, out Bitmap grey))
				{
					return grey;
				}
				var size = bitmap.PixelSize;
				var copy = new WriteableBitmap(size, bitmap.Dpi, PixelFormat.Bgra8888, AlphaFormat.Premul);
				using (ILockedFramebuffer buffer = copy.Lock())
				{
					bitmap.CopyPixels(new PixelRect(size), buffer.Address, buffer.RowBytes * size.Height, buffer.RowBytes);
					var row = new byte[size.Width * 4];
					for (int y = 0; y < size.Height; y++)
					{
						System.Runtime.InteropServices.Marshal.Copy(buffer.Address + y * buffer.RowBytes, row, 0, row.Length);
						for (int x = 0; x < row.Length; x += 4)
						{
							byte luminance = (byte)Math.Round(0.114 * row[x] + 0.587 * row[x + 1] + 0.299 * row[x + 2]);
							row[x] = row[x + 1] = row[x + 2] = luminance;
						}
						System.Runtime.InteropServices.Marshal.Copy(row, 0, buffer.Address + y * buffer.RowBytes, row.Length);
					}
				}
				monochrome.Add(bitmap, copy);
				return copy;
			}
		}

		/// <summary>Sets every opaque magenta pixel (B, G, R, A = 255, 0, 255, 255) of a BGRA buffer to transparent black; returns how many.</summary>
		public static int KeyMagenta(byte[] bgra)
		{
			int count = 0;
			for (int i = 0; i + 3 < bgra.Length; i += 4)
			{
				if (bgra[i] == 255 && bgra[i + 1] == 0 && bgra[i + 2] == 255 && bgra[i + 3] == 255)
				{
					bgra[i] = bgra[i + 1] = bgra[i + 2] = bgra[i + 3] = 0;
					count++;
				}
			}
			return count;
		}

		/// <summary>True for the sources whose magenta is transparent (GIF and BMP, as in the original's toolbar images).</summary>
		public static bool KeysMagenta(string path)
		{
			string ext = System.IO.Path.GetExtension(path).ToLowerInvariant();
			return ext == ".gif" || ext == ".bmp";
		}

		private static Bitmap Load(string path)
		{
			using (Stream stream = AssetLoader.Open(new Uri(FilesUri + path)))
			{
				return Decode(stream, KeysMagenta(path));
			}
		}

		private static KeyNotFoundException Unknown(string name)
		{
			return new KeyNotFoundException("The original has no image resource named '" + name + "' (use the name of Properties/Resources.resx, optionally as Project:Name).");
		}

		private static IconMap LoadMap()
		{
			using (Stream stream = AssetLoader.Open(new Uri(MapUri)))
			using (JsonDocument document = JsonDocument.Parse(stream))
			{
				JsonElement root = document.RootElement;
				var order = root.GetProperty("order").EnumerateArray().Select(e => e.GetString()).ToList();
				var projects = new Dictionary<string, Dictionary<string, IconEntry>>();
				foreach (JsonProperty project in root.GetProperty("projects").EnumerateObject())
				{
					var names = new Dictionary<string, IconEntry>(StringComparer.Ordinal);
					foreach (JsonProperty item in project.Value.GetProperty("names").EnumerateObject())
					{
						string dark = item.Value.TryGetProperty("dark", out JsonElement d) ? d.GetString() : null;
						names[item.Name] = new IconEntry(item.Value.GetProperty("path").GetString(), dark);
					}
					projects[project.Name] = names;
				}
				return new IconMap(order, projects);
			}
		}

		private sealed class IconEntry
		{
			public IconEntry(string path, string dark)
			{
				Path = path;
				Dark = dark;
			}

			public string Path { get; }

			public string Dark { get; }
		}

		private sealed class IconMap
		{
			public IconMap(List<string> order, Dictionary<string, Dictionary<string, IconEntry>> projects)
			{
				Order = order;
				Projects = projects;
				AllNames = order.SelectMany(p => projects[p].Keys).Distinct(StringComparer.Ordinal).OrderBy(n => n, StringComparer.Ordinal).ToList();
			}

			public List<string> Order { get; }

			public Dictionary<string, Dictionary<string, IconEntry>> Projects { get; }

			public List<string> AllNames { get; }

			public IconEntry Find(string name)
			{
				if (string.IsNullOrEmpty(name))
				{
					return null;
				}
				int colon = name.IndexOf(':');
				if (colon > 0)
				{
					return Projects.TryGetValue(name.Substring(0, colon), out var names) && names.TryGetValue(name.Substring(colon + 1), out IconEntry qualified) ? qualified : null;
				}
				foreach (string project in Order)
				{
					if (Projects[project].TryGetValue(name, out IconEntry entry))
					{
						return entry;
					}
				}
				return null;
			}
		}
	}
}
