using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace ApiInventory
{
	internal static class Report
	{
		private static string FilesText(Dictionary<string, int> files, int limit)
		{
			var ordered = files.OrderByDescending(f => f.Value).ThenBy(f => f.Key, StringComparer.Ordinal).ToList();
			string text = string.Join(", ", ordered.Take(limit).Select(f => $"`{f.Key}` ({f.Value})"));
			return ordered.Count > limit ? text + $" (+{ordered.Count - limit} more)" : text;
		}

		private static string MemberText(MemberRec m)
		{
			string t = SigProvider.Short(m.Type.FullName);
			string stat = m.IsStatic && m.Kind != "ctor" ? "static " : "";
			return m.Kind switch
			{
				"ctor" => $"{t}{m.Sig}",
				"field" => $"{stat}{t}.{m.Sig}",
				"property" => $"{stat}{t}.{m.Name}{m.Sig} {{{string.Join(",", m.Accessors)}}}",
				"event" => $"{stat}{t}.{m.Name}{m.Sig} {{{string.Join(",", m.Accessors)}}}",
				_ => $"{stat}{t}.{m.Name}{m.Sig}",
			};
		}

		private static string Esc(string s) => s.Replace("|", "\\|");

		public static string Render(Inventory inv, List<AssemblyScanner> scanners, string repoDir, int filesPerRow)
		{
			var sb = new StringBuilder();
			string commit = Git(repoDir, "rev-parse", "--short", "HEAD");
			sb.AppendLine("# API inventory (pass A)");
			sb.AppendLine();
			sb.AppendLine("What the Core assemblies use from `System.Drawing.Common`, `System.Drawing.Primitives` (types only) and `System.Windows.Forms`, plus every `DllImport`. It is the input of the Drawing route spike (M0.4) and of the compat shims (M1.1, M1.2a).");
			sb.AppendLine();
			sb.AppendLine("- **Generated by:** `dotnet run --project mac/tools/api-inventory` (builds pass A clean, then reads the three output assemblies with `System.Reflection.Metadata`).");
			sb.AppendLine($"- **Commit:** `{commit}`; **SDK:** `{Git(repoDir, "--version", null, null, "dotnet")}`");
			sb.AppendLine($"- **Assemblies read:** {string.Join(", ", scanners.Select(s => $"`{s.Name}` ({s.MethodBodies} method bodies)"))}. File names come from the portable PDBs (the first document of the method containing the use; for field and base-type uses, the file that holds most of the declaring type's code).");
			sb.AppendLine("- **Counting:** a *call site* is one IL instruction (`call`, `callvirt`, `newobj`, `ldfld`, `stfld`, `ldsfld`, `ldtoken`, ...) whose operand is a member reference to that member. Members are distinct by signature (overloads count separately). Property and event accessors are merged into one row. Enum constants are inlined by the compiler, so an enum shows up through the signatures that use it, not through call sites.");
			sb.AppendLine("- **Type uses** = IL type tokens (`castclass`, `isinst`, `box`, `newarr`, ...) + member references + mentions in declarations and signatures (base types, fields, parameters, return types, locals, generic arguments).");
			sb.AppendLine("- **Limits:** only members that the compiler emitted as references are visible. Members are listed under the type that declares them, as the compiler emitted the reference (for example `Image.Width`, not `Bitmap.Width`). Reflection and `dynamic` use is not seen. Scripts (D6) are outside this repository and not scanned.");
			sb.AppendLine();

			var areas = new[] { ("Drawing", "System.Drawing.Common"), ("Forms", "System.Windows.Forms"), ("DrawingPrimitives", "System.Drawing.Primitives") };
			sb.AppendLine("## Summary");
			sb.AppendLine();
			sb.AppendLine("| Area | Types | Ctors | Methods | Properties | Fields | Events | Member call sites |");
			sb.AppendLine("|---|---|---|---|---|---|---|---|");
			foreach (var (area, title) in areas)
			{
				var ms = inv.MembersOf(area).ToList();
				string Count(string kind) => area == "DrawingPrimitives" ? "n/a" : ms.Count(m => m.Kind == kind).ToString(CultureInfo.InvariantCulture);
				sb.AppendLine($"| {title} | {inv.Types.Values.Count(t => Inventory.Area(t.Scope) == area)} | {Count("ctor")} | {Count("method")} | {Count("property")} | {Count("field")} | {Count("event")} | {(area == "DrawingPrimitives" ? "n/a" : ms.Sum(m => m.Calls).ToString(CultureInfo.InvariantCulture))} |");
			}
			sb.AppendLine();
			sb.AppendLine("Types by kind (from the reference assemblies):");
			sb.AppendLine();
			sb.AppendLine("| Area | " + string.Join(" | ", new[] { "enum", "struct", "class", "static class", "interface", "delegate", "unclassified" }) + " |");
			sb.AppendLine("|---|---|---|---|---|---|---|---|");
			foreach (var (area, title) in areas)
			{
				var ts = inv.Types.Values.Where(t => Inventory.Area(t.Scope) == area).ToList();
				string C(string k) => ts.Count(t => t.Kind == k).ToString(CultureInfo.InvariantCulture);
				int known = new[] { "enum", "struct", "class", "static class", "interface", "delegate" }.Sum(k => ts.Count(t => t.Kind == k));
				sb.AppendLine($"| {title} | {C("enum")} | {C("struct")} | {C("class")} | {C("static class")} | {C("interface")} | {C("delegate")} | {ts.Count - known} |");
			}
			sb.AppendLine();
			sb.AppendLine($"P/Invoke: {inv.PInvokes.Count} declarations in {inv.PInvokes.Select(p => p.Module.ToLowerInvariant()).Distinct().Count()} native modules, {inv.PInvokes.Sum(p => p.Calls)} call sites.");
			sb.AppendLine();

			foreach (var (area, title) in areas)
			{
				var ts = inv.Types.Values.Where(t => Inventory.Area(t.Scope) == area)
					.OrderByDescending(t => t.Total).ThenBy(t => t.FullName, StringComparer.Ordinal).ToList();
				sb.AppendLine($"## Types: {title}");
				sb.AppendLine();
				sb.AppendLine("Sorted by total uses.");
				sb.AppendLine();
				sb.AppendLine("| Type | Kind | Uses | IL | Members | Decl | Files |");
				sb.AppendLine("|---|---|---|---|---|---|---|");
				foreach (var t in ts)
				{
					string kind = t.Kind + (t.IsFlags ? " [Flags]" : "");
					sb.AppendLine($"| `{Esc(t.FullName.Replace('+', '.'))}` | {kind} | {t.Total} | {t.IlUses} | {t.MemberUses} | {t.DeclUses} | {FilesText(t.Files, 3)} |");
				}
				sb.AppendLine();
			}

			foreach (var (area, title) in areas.Where(a => a.Item1 != "DrawingPrimitives"))
			{
				var ms = inv.MembersOf(area).OrderByDescending(m => m.Calls).ThenBy(m => MemberText(m), StringComparer.Ordinal).ToList();
				sb.AppendLine($"## Members: {title}");
				sb.AppendLine();
				sb.AppendLine("`Type.Member`, call sites, files (up to " + filesPerRow + ", with the number of call sites in each). Sorted by call sites.");
				sb.AppendLine();
				sb.AppendLine("| Member | Kind | Call sites | Files |");
				sb.AppendLine("|---|---|---|---|");
				foreach (var m in ms)
					sb.AppendLine($"| `{Esc(MemberText(m))}` | {m.Kind} | {m.Calls} | {FilesText(m.Files, filesPerRow)} |");
				sb.AppendLine();
			}

			sb.AppendLine("## P/Invoke (`DllImport`)");
			sb.AppendLine();
			sb.AppendLine("By native module:");
			sb.AppendLine();
			sb.AppendLine("| Module | Declarations | Call sites |");
			sb.AppendLine("|---|---|---|");
			foreach (var g in inv.PInvokes.GroupBy(p => p.Module.ToLowerInvariant()).OrderByDescending(g => g.Sum(p => p.Calls)).ThenBy(g => g.Key, StringComparer.Ordinal))
				sb.AppendLine($"| `{g.Key}` | {g.Count()} | {g.Sum(p => p.Calls)} |");
			sb.AppendLine();
			sb.AppendLine("Every declaration (`Module!EntryPoint → Declaring.Method`), sorted by call sites. A declaration with 0 call sites is unused in the linked sources.");
			sb.AppendLine();
			sb.AppendLine("| Module | Entry point | Declared in | Call sites | Files |");
			sb.AppendLine("|---|---|---|---|---|");
			foreach (var p in inv.PInvokes.OrderByDescending(p => p.Calls).ThenBy(p => p.Module.ToLowerInvariant(), StringComparer.Ordinal).ThenBy(p => p.EntryPoint, StringComparer.Ordinal))
				sb.AppendLine($"| `{p.Module}` | `{p.EntryPoint}` | `{Esc(p.Declaring.Replace('+', '.') + "." + p.Name)}` | {p.Calls} | {FilesText(p.Files, filesPerRow)} |");
			sb.AppendLine();

			sb.AppendLine("## Assembly references per assembly");
			sb.AppendLine();
			foreach (var s in scanners)
				sb.AppendLine($"- `{s.Name}`: {string.Join(", ", s.AssemblyReferenceNames().OrderBy(n => n, StringComparer.Ordinal).Select(n => $"`{n}`"))}");
			sb.AppendLine();
			return sb.ToString();
		}

		public static string Json(Inventory inv)
		{
			var obj = new
			{
				types = inv.Types.Values.OrderBy(t => t.FullName, StringComparer.Ordinal).Select(t => new
				{
					t.Scope, t.FullName, t.Kind, t.IsFlags, t.IlUses, t.MemberUses, t.DeclUses, files = t.Files,
				}),
				members = inv.Members.Values.OrderBy(m => m.Type.FullName, StringComparer.Ordinal).ThenBy(m => m.Name, StringComparer.Ordinal).Select(m => new
				{
					scope = m.Type.Scope, type = m.Type.FullName, m.Kind, m.Name, m.Sig, m.IsStatic, accessors = m.Accessors, m.Calls, files = m.Files,
				}),
				pinvoke = inv.PInvokes.Select(p => new { p.Module, p.EntryPoint, p.Declaring, p.Name, p.Assembly, p.Calls, files = p.Files }),
			};
			return JsonSerializer.Serialize(obj, new JsonSerializerOptions { WriteIndented = true });
		}

		private static string Git(string repoDir, string a, string b = null, string c = null, string exe = "git")
		{
			try
			{
				var psi = new ProcessStartInfo(exe) { WorkingDirectory = repoDir, RedirectStandardOutput = true, RedirectStandardError = true };
				psi.ArgumentList.Add(a);
				if (b != null) psi.ArgumentList.Add(b);
				if (c != null) psi.ArgumentList.Add(c);
				using var p = Process.Start(psi)!;
				string o = p.StandardOutput.ReadToEnd().Trim();
				p.WaitForExit();
				return o;
			}
			catch
			{
				return "unknown";
			}
		}
	}
}
