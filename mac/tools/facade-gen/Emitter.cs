using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;

namespace FacadeGen
{
	/// <summary>Counters of one run.</summary>
	internal sealed class EmitStats
	{
		public int Types { get; set; }

		public int Members { get; set; }

		public int PartialMerges { get; set; }

		public int HandWrittenComplete { get; set; }
	}

	/// <summary>
	/// Writes the C# of the facade: for every visible type of the reference assemblies a declaration with the public and protected members, whose bodies throw
	/// <see cref="NotSupportedException"/> (the message names the member). What a hand-written part of the same partial type already declares is left out
	/// (<see cref="HandWrittenIndex"/>). Exceptions to "every body throws" (they are called by the runtime, or by cleanup code, and must not fail): <c>Dispose</c>
	/// does nothing (an override calls the base), <c>ToString</c>, <c>GetHashCode</c> and <c>Equals(object)</c> overrides call the base, and <c>==</c> and <c>!=</c> of a type with itself
	/// compare references (classes) or call <c>Equals(object)</c> (structs).
	/// </summary>
	internal sealed class Emitter
	{
		private const BindingFlags Declared = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

		private sealed class Member
		{
			public int Group { get; init; }

			public string Sort { get; init; }

			public string Text { get; init; }
		}

		private enum Kind
		{
			Class,
			Struct,
			Interface,
			Enum,
			Delegate,
		}

		private readonly ReferenceSurface surface;

		private readonly HandWrittenIndex hand;

		private readonly SortedSet<string> omitted = new SortedSet<string>(StringComparer.Ordinal);

		private readonly List<string> problems = new List<string>();

		public EmitStats Stats { get; } = new EmitStats();

		/// <summary>Types, interfaces and members of the reference that the facade does not declare, with the reason (written to omitted.txt).</summary>
		public IReadOnlyCollection<string> Omitted => omitted;

		/// <summary>Findings that make the run fail (a hand-written type that is not partial and lacks members, a base class that differs).</summary>
		public IReadOnlyList<string> Problems => problems;

		public void AddProblem(string problem) => problems.Add(problem);

		public Emitter(ReferenceSurface surface, HandWrittenIndex hand)
		{
			this.surface = surface;
			this.hand = hand;
		}

		// ---- files ----

		/// <summary>The relative path (inside the Generated folder) and the text of a top-level type, or null when a hand-written complete type covers it.</summary>
		public (string Path, string Text)? EmitFile(Type t)
		{
			if (IsExcluded(t))
			{
				omitted.Add("type " + Names.Display(t) + ": declares a compiler-generated fixed buffer, a Win32 interop type");
				return null;
			}
			string body = EmitType(t);
			if (body.Length == 0)
			{
				return null;
			}
			var sb = new StringBuilder();
			sb.Append("// <auto-generated>\n");
			sb.Append("// Generated by mac/tools/facade-gen from the reference assemblies of the Windows Desktop pack. Do not edit: change the generator, or declare the member in the hand-written\n");
			sb.Append("// partial type (the generator leaves out what a hand-written part declares). Every body throws NotSupportedException (Dispose does nothing; ToString, GetHashCode, Equals and == use the base).\n");
			sb.Append("// </auto-generated>\n");
			sb.Append("#nullable disable\n");
			sb.Append("#pragma warning disable CS0067, CS0108, CS0109, CS0114, CS0169, CS0219, CS0414, CS0612, CS0618, CS0628, CS0649, CS0659, CS0660, CS0661, CS0672, CS0809, CS1591, CS8981, CA1416, SYSLIB0011\n");
			sb.Append('\n');
			sb.Append("namespace ").Append(t.Namespace).Append('\n').Append("{\n");
			sb.Append(Indent(body, 1));
			sb.Append("}\n");
			string path = (t.Namespace ?? "") + "/" + Names.StripArity(t.Name) + (t.IsGenericTypeDefinition ? "`" + t.GetGenericArguments().Length : "") + ".g.cs";
			return (path, sb.ToString());
		}

		public static string StubFile()
		{
			var sb = new StringBuilder();
			sb.Append("// <auto-generated>\n");
			sb.Append("// Generated by mac/tools/facade-gen. The exception that every generated body throws.\n");
			sb.Append("// </auto-generated>\n");
			sb.Append("#nullable disable\n\n");
			sb.Append("internal static class FacadeStub\n{\n");
			sb.Append("\tinternal static global::System.NotSupportedException Member(string name) => new global::System.NotSupportedException(name + \" is not yet supported on macOS (ComicRack script compatibility layer)\");\n");
			sb.Append("}\n");
			return sb.ToString();
		}

		// ---- types ----

		private static bool IsExcluded(Type t)
		{
			return t.GetNestedTypes(BindingFlags.Public | BindingFlags.NonPublic).Any(n => ReferenceSurface.IsVisible(n) && IsCompilerGenerated(n));
		}

		private static bool IsCompilerGenerated(Type t) => t.Name.IndexOf('<') >= 0;

		/// <summary>True for a type the facade does not declare (see <see cref="IsExcluded"/>), also as an element, argument or nested type: a member that names it is left out too.</summary>
		private static bool IsHidden(Type t)
		{
			if (t.HasElementType)
			{
				return IsHidden(t.GetElementType());
			}
			if (t.IsGenericParameter)
			{
				return false;
			}
			if (t.IsConstructedGenericType)
			{
				return IsHidden(t.GetGenericTypeDefinition()) || t.GenericTypeArguments.Any(IsHidden);
			}
			return IsCompilerGenerated(t) || IsExcluded(t) || t.IsNested && IsHidden(t.DeclaringType);
		}

		private static bool IsHidden(IEnumerable<ParameterInfo> parameters) => parameters.Any(p => IsHidden(p.ParameterType));

		private void Skipped(Type owner, string member, Type hidden)
		{
			Type t = hidden;
			while (t.HasElementType)
			{
				t = t.GetElementType();
			}
			omitted.Add("member " + Names.Display(owner) + "." + member + ": uses the omitted type " + (t.FullName ?? t.Name));
		}

		private static Kind KindOf(Type t)
		{
			if (t.IsEnum)
			{
				return Kind.Enum;
			}
			if (t.IsInterface)
			{
				return Kind.Interface;
			}
			if (t.IsValueType)
			{
				return Kind.Struct;
			}
			if (t.BaseType != null && (t.BaseType.FullName == "System.MulticastDelegate" || t.BaseType.FullName == "System.Delegate"))
			{
				return Kind.Delegate;
			}
			return Kind.Class;
		}

		private static string Access(MethodBase m) => m.IsPublic ? "public" : m.IsFamily ? "protected" : m.IsFamilyOrAssembly ? "protected internal" : null;

		private static string Access(FieldInfo f) => f.IsPublic ? "public" : f.IsFamily ? "protected" : f.IsFamilyOrAssembly ? "protected internal" : null;

		private static string Access(Type t)
		{
			if (!t.IsNested)
			{
				return "public";
			}
			return t.IsNestedPublic ? "public" : t.IsNestedFamily ? "protected" : "protected internal";
		}

		private static int Rank(string access) => access == "public" ? 3 : access == "protected internal" ? 2 : access == "protected" ? 1 : 0;

		private static string Indent(string text, int tabs)
		{
			if (tabs == 0 || text.Length == 0)
			{
				return text;
			}
			string pad = new string('\t', tabs);
			var sb = new StringBuilder();
			foreach (string line in text.Split('\n'))
			{
				if (line.Length > 0)
				{
					sb.Append(pad).Append(line);
				}
				sb.Append('\n');
			}
			// the split leaves one empty element after the final newline
			if (sb.Length > 0)
			{
				sb.Length--;
			}
			return sb.ToString();
		}

		private static string Throw(string display) => "throw global::FacadeStub.Member(" + Names.Quote(display) + ")";

		/// <summary>The declaration of a type with its members, no indentation, ending with a newline; empty when nothing has to be generated.</summary>
		private string EmitType(Type t)
		{
			Kind kind = KindOf(t);
			HandType h = hand.Find(t.FullName);
			if (h != null)
			{
				if (!string.Equals(h.Kind, kind == Kind.Delegate ? "delegate" : kind.ToString().ToLowerInvariant(), StringComparison.Ordinal))
				{
					problems.Add(t.FullName + ": declared by hand as a " + h.Kind + " but the reference declares a " + kind.ToString().ToLowerInvariant());
					return "";
				}
				if (kind == Kind.Enum || kind == Kind.Delegate)
				{
					Stats.HandWrittenComplete++;
					return "";
				}
			}
			if (kind == Kind.Enum)
			{
				Stats.Types++;
				return EmitEnum(t);
			}
			if (kind == Kind.Delegate)
			{
				Stats.Types++;
				return EmitDelegate(t);
			}
			var members = new List<Member>();
			CollectMembers(t, kind, h, members);
			var nested = new List<Member>();
			foreach (Type n in t.GetNestedTypes(BindingFlags.Public | BindingFlags.NonPublic).Where(ReferenceSurface.IsVisible).Where(n => !IsCompilerGenerated(n)).OrderBy(n => n.Name, StringComparer.Ordinal))
			{
				string text = EmitType(n);
				if (text.Length > 0)
				{
					nested.Add(new Member { Group = 9, Sort = n.Name, Text = text });
				}
			}
			if (h != null && !h.IsPartial)
			{
				Stats.HandWrittenComplete++;
				if (members.Count > 0)
				{
					problems.Add(t.FullName + ": declared by hand and not partial, but it lacks " + members.Count + " member(s) of the reference (make it partial): "
						+ string.Join("; ", members.Take(6).Select(m => m.Sort)));
				}
				return "";
			}
			string baseList = BaseList(t, kind, h, members);
			if (h != null && members.Count == 0 && nested.Count == 0 && baseList.Length == 0)
			{
				Stats.HandWrittenComplete++;
				return "";
			}
			if (h != null)
			{
				Stats.PartialMerges++;
			}
			Stats.Types++;
			Stats.Members += members.Count;
			var sb = new StringBuilder();
			sb.Append(Access(t)).Append(' ');
			if (h == null && kind == Kind.Class)
			{
				if (t.IsAbstract && t.IsSealed)
				{
					sb.Append("static ");
				}
				else if (t.IsAbstract)
				{
					sb.Append("abstract ");
				}
				else if (t.IsSealed)
				{
					sb.Append("sealed ");
				}
			}
			sb.Append("partial ");
			sb.Append(kind == Kind.Interface ? "interface " : kind == Kind.Struct ? "struct " : "class ");
			sb.Append(Names.Identifier(Names.StripArity(t.Name)));
			sb.Append(GenericParameterList(t));
			sb.Append(baseList);
			sb.Append(Constraints(t));
			sb.Append('\n').Append("{\n");
			int lastGroup = -1;
			foreach (Member m in members.Concat(nested).OrderBy(m => m.Group).ThenBy(m => m.Sort, StringComparer.Ordinal))
			{
				if (lastGroup >= 0 && (lastGroup != m.Group || m.Group == 9))
				{
					sb.Append('\n');
				}
				lastGroup = m.Group;
				sb.Append(Indent(m.Text, 1));
			}
			sb.Append("}\n");
			return sb.ToString();
		}

		private string GenericParameterList(Type t)
		{
			if (!t.IsGenericTypeDefinition)
			{
				return "";
			}
			int skip = t.IsNested && t.DeclaringType.IsGenericTypeDefinition ? t.DeclaringType.GetGenericArguments().Length : 0;
			Type[] own = t.GetGenericArguments().Skip(skip).ToArray();
			if (own.Length == 0)
			{
				return "";
			}
			return "<" + string.Join(", ", own.Select(a => Variance(a) + Names.Identifier(a.Name))) + ">";
		}

		private static string Variance(Type parameter)
		{
			GenericParameterAttributes attributes = parameter.GenericParameterAttributes & GenericParameterAttributes.VarianceMask;
			return attributes == GenericParameterAttributes.Covariant ? "out " : attributes == GenericParameterAttributes.Contravariant ? "in " : "";
		}

		private string Constraints(Type t)
		{
			if (!t.IsGenericTypeDefinition)
			{
				return "";
			}
			int skip = t.IsNested && t.DeclaringType.IsGenericTypeDefinition ? t.DeclaringType.GetGenericArguments().Length : 0;
			return Constraints(t.GetGenericArguments().Skip(skip).ToArray());
		}

		private static string Constraints(Type[] parameters)
		{
			var sb = new StringBuilder();
			foreach (Type p in parameters)
			{
				var list = new List<string>();
				GenericParameterAttributes attributes = p.GenericParameterAttributes;
				bool isStruct = (attributes & GenericParameterAttributes.NotNullableValueTypeConstraint) != 0;
				if ((attributes & GenericParameterAttributes.ReferenceTypeConstraint) != 0)
				{
					list.Add("class");
				}
				if (isStruct)
				{
					list.Add("struct");
				}
				foreach (Type c in p.GetGenericParameterConstraints())
				{
					if (!(isStruct && c.FullName == "System.ValueType"))
					{
						list.Add(Names.Render(c));
					}
				}
				if ((attributes & GenericParameterAttributes.DefaultConstructorConstraint) != 0 && !isStruct)
				{
					list.Add("new()");
				}
				if (list.Count > 0)
				{
					sb.Append(" where ").Append(Names.Identifier(p.Name)).Append(" : ").Append(string.Join(", ", list));
				}
			}
			return sb.ToString();
		}

		// ---- enums and delegates ----

		private string EmitEnum(Type t)
		{
			var sb = new StringBuilder();
			if (t.CustomAttributes.Any(a => a.AttributeType.FullName == "System.FlagsAttribute"))
			{
				sb.Append("[global::System.Flags]\n");
			}
			sb.Append(Access(t)).Append(" enum ").Append(Names.Identifier(t.Name));
			Type underlying = t.GetEnumUnderlyingType();
			if (underlying.FullName != "System.Int32")
			{
				sb.Append(" : ").Append(Names.Render(underlying));
			}
			sb.Append('\n').Append("{\n");
			foreach (FieldInfo f in t.GetFields(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly))
			{
				object raw = f.GetRawConstantValue();
				sb.Append('\t').Append(Names.Identifier(f.Name)).Append(" = ").Append(Convert.ToString(raw, CultureInfo.InvariantCulture)).Append(",\n");
			}
			sb.Append("}\n");
			return sb.ToString();
		}

		private string EmitDelegate(Type t)
		{
			MethodInfo invoke = t.GetMethod("Invoke");
			var sb = new StringBuilder();
			sb.Append(Access(t)).Append(" delegate ").Append(Names.Render(invoke.ReturnType)).Append(' ').Append(Names.Identifier(Names.StripArity(t.Name)));
			sb.Append(GenericParameterList(t)).Append('(').Append(ParameterList(invoke.GetParameters(), defaults: true)).Append(')').Append(Constraints(t)).Append(";\n");
			return sb.ToString();
		}

		// ---- base list ----

		private static bool LooksLikeInterface(string name) => name.Length > 1 && name[0] == 'I' && char.IsUpper(name[1]);

		private static bool Lists(HandType h, Type type)
		{
			string simple = Names.StripArity(type.Name);
			string full = Names.Display(type);
			foreach (string written in h.BaseListText)
			{
				string text = written.Replace("global::", "");
				int generic = text.IndexOf('<');
				if (generic >= 0)
				{
					text = text.Substring(0, generic);
				}
				if (text.Contains('.') ? text == full : text == simple)
				{
					return true;
				}
			}
			return false;
		}

		/// <summary>The interfaces that a type lists itself: those of the reference that its base type does not have already, without those that another listed one brings.</summary>
		private List<Type> DirectInterfaces(Type t, out List<Type> toImplement)
		{
			var baseKeys = new HashSet<string>(t.BaseType?.GetInterfaces().Select(i => i.ToString()) ?? Enumerable.Empty<string>(), StringComparer.Ordinal);
			var candidates = new List<Type>();
			foreach (Type i in t.GetInterfaces().OrderBy(i => i.ToString(), StringComparer.Ordinal))
			{
				if (baseKeys.Contains(i.ToString()))
				{
					continue;
				}
				if (!surface.IsExposed(i))
				{
					if (ReferenceSurface.IsVisible(i))
					{
						omitted.Add("interface " + Names.Display(i) + " of " + Names.Display(t) + ": not part of the facade");
					}
					continue;
				}
				candidates.Add(i);
			}
			var implied = new HashSet<string>(candidates.SelectMany(i => i.GetInterfaces()).Select(i => i.ToString()), StringComparer.Ordinal);
			toImplement = candidates;
			return candidates.Where(i => !implied.Contains(i.ToString())).ToList();
		}

		private string BaseList(Type t, Kind kind, HandType h, List<Member> members)
		{
			var items = new List<string>();
			Type baseType = t.BaseType;
			if (kind == Kind.Class && baseType != null && baseType.FullName != "System.Object")
			{
				bool handHasBase = h != null && h.BaseList.Any(name => !LooksLikeInterface(name));
				if (handHasBase)
				{
					string written = h.BaseList.First(name => !LooksLikeInterface(name));
					if (written != Names.StripArity(baseType.Name))
					{
						problems.Add(t.FullName + ": declared by hand with the base class " + written + " but the reference derives from " + Names.Display(baseType));
					}
				}
				else
				{
					items.Add(Names.Render(baseType));
				}
			}
			if (kind == Kind.Class || kind == Kind.Struct)
			{
				List<Type> direct = DirectInterfaces(t, out List<Type> toImplement);
				foreach (Type i in direct)
				{
					if (h == null || !Lists(h, i))
					{
						items.Add(Names.Render(i));
					}
				}
				ExplicitImplementations(t, h, toImplement, members);
			}
			else if (kind == Kind.Interface)
			{
				foreach (Type i in t.GetInterfaces().Where(surface.IsExposed).OrderBy(i => i.ToString(), StringComparer.Ordinal))
				{
					bool implied = t.GetInterfaces().Any(j => !j.Equals(i) && j.GetInterfaces().Any(k => k.Equals(i)));
					if (!implied)
					{
						items.Add(Names.Render(i));
					}
				}
			}
			return items.Count == 0 ? "" : " : " + string.Join(", ", items);
		}

		// ---- members ----

		private void CollectMembers(Type t, Kind kind, HandType h, List<Member> members)
		{
			bool isInterface = kind == Kind.Interface;
			string typeName = Names.Display(t);
			HashSet<string> have = h?.Members ?? new HashSet<string>();
			if (h != null && kind == Kind.Class && !h.HasExplicitCtor)
			{
				have = new HashSet<string>(have, StringComparer.Ordinal) { "C:()" };
			}

			foreach (FieldInfo f in t.GetFields(Declared))
			{
				string access = Access(f);
				if (access == null)
				{
					continue;
				}
				if (IsHidden(f.FieldType))
				{
					Skipped(t, f.Name, f.FieldType);
					continue;
				}
				if (have.Contains(MemberKeys.Field(f)))
				{
					continue;
				}
				members.Add(new Member { Group = f.IsLiteral ? 0 : 1, Sort = f.Name, Text = EmitField(f, access) });
			}

			if (kind == Kind.Class || kind == Kind.Struct)
			{
				var ctors = t.GetConstructors(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.DeclaredOnly).Where(c => Access(c) != null).ToList();
				foreach (ConstructorInfo c in ctors)
				{
					if (kind == Kind.Class && h != null && h.IsPartial && !h.HasExplicitCtor && c.GetParameters().Length == 0)
					{
						// The hand-written part relies on the implicit parameterless constructor. Another constructor of this partial type would remove it,
						// so it is declared (empty body, like the implicit one).
						members.Add(new Member { Group = 2, Sort = "", Text = Access(c) + " " + Names.Identifier(Names.StripArity(t.Name)) + "()" + BaseCtorCall(t) + "\n{\n}\n" });
						continue;
					}
					if (have.Contains(MemberKeys.Constructor(c)))
					{
						continue;
					}
					if (IsHidden(c.GetParameters()))
					{
						Skipped(t, "ctor", c.GetParameters().First(p => IsHidden(p.ParameterType)).ParameterType);
						continue;
					}
					members.Add(new Member { Group = 2, Sort = MemberKeys.Parameters(c.GetParameters()), Text = EmitConstructor(t, c, typeName) });
				}
				bool synthesize = kind == Kind.Class && ctors.Count == 0 && !(t.IsAbstract && t.IsSealed) && (h == null || h.IsPartial && !h.HasExplicitCtor);
				if (synthesize)
				{
					members.Add(new Member { Group = 2, Sort = "", Text = "internal " + Names.Identifier(Names.StripArity(t.Name)) + "()" + BaseCtorCall(t) + "\n{\n}\n" });
				}
			}

			foreach (PropertyInfo p in t.GetProperties(Declared))
			{
				MethodInfo get = p.GetMethod;
				MethodInfo set = p.SetMethod;
				string accessGet = get == null ? null : isInterface ? "public" : Access(get);
				string accessSet = set == null ? null : isInterface ? "public" : Access(set);
				if (accessGet == null && accessSet == null)
				{
					continue;
				}
				if (p.Name.IndexOf('.') >= 0)
				{
					continue;
				}
				if (IsHidden(p.PropertyType) || IsHidden(p.GetIndexParameters()))
				{
					Skipped(t, p.Name, IsHidden(p.PropertyType) ? p.PropertyType : p.GetIndexParameters().First(x => IsHidden(x.ParameterType)).ParameterType);
					continue;
				}
				if (have.Contains(MemberKeys.Property(p)))
				{
					continue;
				}
				members.Add(new Member { Group = 3, Sort = MemberKeys.Property(p), Text = EmitProperty(t, p, get, set, accessGet, accessSet, isInterface, typeName) });
			}

			foreach (EventInfo e in t.GetEvents(Declared))
			{
				MethodInfo add = e.AddMethod;
				string access = add == null ? null : isInterface ? "public" : Access(add);
				if (access == null || e.Name.IndexOf('.') >= 0)
				{
					continue;
				}
				if (IsHidden(e.EventHandlerType))
				{
					Skipped(t, e.Name, e.EventHandlerType);
					continue;
				}
				if (have.Contains(MemberKeys.Event(e)))
				{
					continue;
				}
				members.Add(new Member { Group = 4, Sort = e.Name, Text = EmitEvent(e, add, access, isInterface, typeName) });
			}

			foreach (MethodInfo m in t.GetMethods(Declared))
			{
				string access = isInterface ? (m.IsPublic ? "public" : null) : Access(m);
				if (access == null || m.IsStatic && isInterface)
				{
					continue;
				}
				if (m.IsSpecialName && !m.Name.StartsWith("op_", StringComparison.Ordinal))
				{
					continue;
				}
				if (m.Name == "Finalize" && m.GetParameters().Length == 0 || m.Name.IndexOf('.') >= 0)
				{
					continue;
				}
				if (IsHidden(m.ReturnType) || IsHidden(m.GetParameters()))
				{
					Skipped(t, m.Name, IsHidden(m.ReturnType) ? m.ReturnType : m.GetParameters().First(p => IsHidden(p.ParameterType)).ParameterType);
					continue;
				}
				if (have.Contains(MemberKeys.Method(m)))
				{
					continue;
				}
				string text = m.IsSpecialName ? EmitOperator(t, m, typeName) : EmitMethod(t, m, access, isInterface, typeName);
				if (text == null)
				{
					continue;
				}
				members.Add(new Member { Group = m.IsSpecialName ? 6 : 5, Sort = MemberKeys.Method(m), Text = text });
			}
		}

		private string EmitField(FieldInfo f, string access)
		{
			string type = Names.Render(f.FieldType);
			if (f.IsLiteral)
			{
				return access + " const " + type + " " + Names.Identifier(f.Name) + " = " + Names.Literal(f.GetRawConstantValue(), f.FieldType) + ";\n";
			}
			var sb = new StringBuilder(access);
			if (f.IsStatic)
			{
				sb.Append(" static");
			}
			if (f.IsInitOnly)
			{
				sb.Append(" readonly");
			}
			sb.Append(' ').Append(type).Append(' ').Append(Names.Identifier(f.Name));
			if (f.IsStatic && f.IsInitOnly)
			{
				sb.Append(" = default");
			}
			return sb.Append(";\n").ToString();
		}

		private string EmitConstructor(Type t, ConstructorInfo c, string typeName)
		{
			string access = Access(c);
			string name = Names.Identifier(Names.StripArity(t.Name));
			var sb = new StringBuilder();
			sb.Append(access).Append(' ').Append(name).Append('(').Append(ParameterList(c.GetParameters(), defaults: true)).Append(')');
			if (!t.IsValueType)
			{
				sb.Append(BaseCtorCall(t));
			}
			sb.Append('\n').Append("{\n\t").Append(Throw(typeName + ".ctor")).Append(";\n}\n");
			return sb.ToString();
		}

		/// <summary>The call of a base constructor that a derived constructor needs when the base has no parameterless one (arguments are typed defaults, so the overload is exact).</summary>
		private string BaseCtorCall(Type t)
		{
			Type b = t.BaseType;
			if (b == null || t.IsValueType || b.FullName == "System.Object")
			{
				return "";
			}
			var ctors = b.GetConstructors(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.DeclaredOnly).Where(c => Access(c) != null).ToList();
			if (ctors.Count == 0 || ctors.Any(c => c.GetParameters().Length == 0))
			{
				return "";
			}
			ConstructorInfo pick = ctors.Where(c => c.GetParameters().All(p => !p.ParameterType.IsByRef && !p.ParameterType.IsPointer))
				.OrderBy(c => c.GetParameters().Length).ThenBy(c => MemberKeys.Parameters(c.GetParameters()), StringComparer.Ordinal).FirstOrDefault();
			if (pick == null)
			{
				return "";
			}
			return " : base(" + string.Join(", ", pick.GetParameters().Select(p => "default(" + Names.Render(p.ParameterType) + ")")) + ")";
		}

		private static string MethodModifiers(MethodBase m)
		{
			bool newSlot = (m.Attributes & MethodAttributes.NewSlot) != 0;
			if (m.IsStatic)
			{
				return "static ";
			}
			if (m.IsAbstract)
			{
				return newSlot ? "abstract " : "abstract override ";
			}
			if (m.IsVirtual)
			{
				if (m.IsFinal)
				{
					return newSlot ? "" : "sealed override ";
				}
				return newSlot ? "virtual " : "override ";
			}
			return "";
		}

		private string EmitMethod(Type t, MethodInfo m, string access, bool isInterface, string typeName)
		{
			var sb = new StringBuilder();
			if (!isInterface)
			{
				sb.Append(access).Append(' ').Append(MethodModifiers(m));
			}
			sb.Append(Names.Render(m.ReturnType)).Append(' ').Append(Names.Identifier(m.Name));
			Type[] generic = m.IsGenericMethodDefinition ? m.GetGenericArguments() : Type.EmptyTypes;
			if (generic.Length > 0)
			{
				sb.Append('<').Append(string.Join(", ", generic.Select(g => Variance(g) + Names.Identifier(g.Name)))).Append('>');
			}
			ParameterInfo[] ps = m.GetParameters();
			sb.Append('(').Append(ParameterList(ps, defaults: true)).Append(')');
			sb.Append(Constraints(generic));
			if (isInterface || m.IsAbstract)
			{
				return sb.Append(";\n").ToString();
			}
			sb.Append(Body(m, ps, typeName + "." + m.Name)).Append('\n');
			return sb.ToString();
		}

		/// <summary>The body of a method. A cleanup call, or a method that the runtime calls on any object, must not fail: Dispose does nothing, ToString/GetHashCode/Equals call the base.</summary>
		private static string Body(MethodInfo m, ParameterInfo[] ps, string display)
		{
			bool isOverride = m.IsVirtual && (m.Attributes & MethodAttributes.NewSlot) == 0 && !m.IsStatic;
			if (m.Name == "Dispose" && m.ReturnType.FullName == "System.Void" && (ps.Length == 0 || ps.Length == 1 && ps[0].ParameterType.FullName == "System.Boolean"))
			{
				return isOverride ? " => base.Dispose(" + (ps.Length == 1 ? Names.Identifier(ps[0].Name) : "") + ");" : "\n{\n}";
			}
			if (isOverride && m.Name == "ToString" && ps.Length == 0)
			{
				return " => base.ToString();";
			}
			if (isOverride && m.Name == "GetHashCode" && ps.Length == 0)
			{
				return " => base.GetHashCode();";
			}
			if (isOverride && m.Name == "Equals" && ps.Length == 1 && ps[0].ParameterType.FullName == "System.Object")
			{
				return " => base.Equals(" + Names.Identifier(ps[0].Name) + ");";
			}
			return " => " + Throw(display) + ";";
		}

		private string EmitProperty(Type t, PropertyInfo p, MethodInfo get, MethodInfo set, string accessGet, string accessSet, bool isInterface, string typeName)
		{
			string propertyAccess = Rank(accessGet) >= Rank(accessSet) ? accessGet : accessSet;
			MethodInfo primary = Rank(accessGet) >= Rank(accessSet) ? get : set;
			ParameterInfo[] index = p.GetIndexParameters();
			var sb = new StringBuilder();
			if (!isInterface)
			{
				sb.Append(propertyAccess).Append(' ').Append(MethodModifiers(primary));
			}
			if (index.Length > 0 && p.Name != "Item")
			{
				sb.Insert(0, "[global::System.Runtime.CompilerServices.IndexerName(" + Names.Quote(p.Name) + ")]\n");
			}
			sb.Append(Names.Render(p.PropertyType)).Append(' ');
			sb.Append(index.Length > 0 ? "this[" + ParameterList(index, defaults: false) + "]" : Names.Identifier(p.Name));
			bool noBody = isInterface || primary.IsAbstract;
			string display = typeName + "." + p.Name;
			sb.Append("\n{\n");
			if (accessGet != null)
			{
				sb.Append('\t').Append(accessGet != propertyAccess && !isInterface ? accessGet + " " : "").Append("get").Append(noBody ? ";" : " => " + Throw(display) + ";").Append('\n');
			}
			if (accessSet != null)
			{
				sb.Append('\t').Append(accessSet != propertyAccess && !isInterface ? accessSet + " " : "").Append("set").Append(noBody ? ";" : " => " + Throw(display) + ";").Append('\n');
			}
			sb.Append("}\n");
			return sb.ToString();
		}

		private string EmitEvent(EventInfo e, MethodInfo add, string access, bool isInterface, string typeName)
		{
			var sb = new StringBuilder();
			if (!isInterface)
			{
				sb.Append(access).Append(' ').Append(MethodModifiers(add));
			}
			sb.Append("event ").Append(Names.Render(e.EventHandlerType)).Append(' ').Append(Names.Identifier(e.Name));
			if (isInterface || add.IsAbstract)
			{
				return sb.Append(";\n").ToString();
			}
			string display = typeName + "." + e.Name;
			sb.Append("\n{\n\tadd => ").Append(Throw(display)).Append(";\n\tremove => ").Append(Throw(display)).Append(";\n}\n");
			return sb.ToString();
		}

		private static readonly Dictionary<string, string> OperatorTokens = new Dictionary<string, string>(StringComparer.Ordinal)
		{
			["op_Addition"] = "+",
			["op_Subtraction"] = "-",
			["op_Multiply"] = "*",
			["op_Division"] = "/",
			["op_Modulus"] = "%",
			["op_BitwiseAnd"] = "&",
			["op_BitwiseOr"] = "|",
			["op_ExclusiveOr"] = "^",
			["op_LeftShift"] = "<<",
			["op_RightShift"] = ">>",
			["op_Equality"] = "==",
			["op_Inequality"] = "!=",
			["op_LessThan"] = "<",
			["op_GreaterThan"] = ">",
			["op_LessThanOrEqual"] = "<=",
			["op_GreaterThanOrEqual"] = ">=",
			["op_UnaryPlus"] = "+",
			["op_UnaryNegation"] = "-",
			["op_LogicalNot"] = "!",
			["op_OnesComplement"] = "~",
			["op_Increment"] = "++",
			["op_Decrement"] = "--",
			["op_True"] = "true",
			["op_False"] = "false",
		};

		private string EmitOperator(Type t, MethodInfo m, string typeName)
		{
			ParameterInfo[] ps = m.GetParameters();
			string display = typeName + "." + m.Name;
			string parameters = ParameterList(ps, defaults: false);
			if (m.Name == "op_Implicit" || m.Name == "op_Explicit")
			{
				return "public static " + (m.Name == "op_Implicit" ? "implicit" : "explicit") + " operator " + Names.Render(m.ReturnType) + "(" + parameters + ") => " + Throw(display) + ";\n";
			}
			if (!OperatorTokens.TryGetValue(m.Name, out string token))
			{
				problems.Add(t.FullName + ": unknown operator " + m.Name);
				return null;
			}
			string body = Throw(display);
			bool equality = m.Name == "op_Equality" || m.Name == "op_Inequality";
			if (equality && ps.Length == 2 && ps[0].ParameterType.Equals(t) && ps[1].ParameterType.Equals(t))
			{
				// Like Equals: a comparison is made by collections and by the runtime on any object, so it must not fail. Classes compare references, structs call Equals(object).
				string a = Names.Identifier(ps[0].Name);
				string b = Names.Identifier(ps[1].Name);
				string same = t.IsValueType ? "((object)" + a + ").Equals(" + b + ")" : "global::System.Object.ReferenceEquals(" + a + ", " + b + ")";
				body = m.Name == "op_Equality" ? same : "!" + same;
			}
			return "public static " + Names.Render(m.ReturnType) + " operator " + token + "(" + parameters + ") => " + body + ";\n";
		}

		// ---- explicit interface implementations ----

		private void ExplicitImplementations(Type t, HandType h, List<Type> interfaces, List<Member> members)
		{
			if (interfaces.Count == 0)
			{
				return;
			}
			MethodInfo[] methods = t.GetMethods(BindingFlags.Public | BindingFlags.Instance);
			PropertyInfo[] properties = t.GetProperties(BindingFlags.Public | BindingFlags.Instance);
			EventInfo[] events = t.GetEvents(BindingFlags.Public | BindingFlags.Instance);
			string typeName = Names.Display(t);
			foreach (Type i in interfaces)
			{
				if (h != null && Lists(h, i))
				{
					continue;
				}
				string iName = Names.StripArity(i.Name);
				string iRender = Names.Render(i);
				foreach (MethodInfo im in i.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly).Where(m => !m.IsSpecialName))
				{
					string key = MemberKeys.Method(im, iName);
					if (h != null && h.Members.Contains(key) || methods.Any(m => m.Name == im.Name && SameParameters(m.GetParameters(), im.GetParameters()) && m.GetGenericArguments().Length == im.GetGenericArguments().Length && m.ReturnType.ToString() == im.ReturnType.ToString()))
					{
						continue;
					}
					ParameterInfo[] ps = im.GetParameters();
					Type[] generic = im.IsGenericMethodDefinition ? im.GetGenericArguments() : Type.EmptyTypes;
					string text = Names.Render(im.ReturnType) + " " + iRender + "." + Names.Identifier(im.Name)
						+ (generic.Length > 0 ? "<" + string.Join(", ", generic.Select(g => Names.Identifier(g.Name))) + ">" : "")
						+ "(" + ParameterList(ps, defaults: false, allowParams: false) + ")"
						+ (im.Name == "Dispose" && ps.Length == 0 ? "\n{\n}\n" : " => " + Throw(typeName + "." + iName + "." + im.Name) + ";\n");
					members.Add(new Member { Group = 7, Sort = key, Text = text });
				}
				foreach (PropertyInfo ip in i.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
				{
					string key = MemberKeys.Property(ip, iName);
					ParameterInfo[] index = ip.GetIndexParameters();
					if (h != null && h.Members.Contains(key) || properties.Any(p => p.Name == ip.Name && SameParameters(p.GetIndexParameters(), index) && p.PropertyType.ToString() == ip.PropertyType.ToString()))
					{
						continue;
					}
					string display = typeName + "." + iName + "." + ip.Name;
					var sb = new StringBuilder();
					sb.Append(Names.Render(ip.PropertyType)).Append(' ').Append(iRender).Append('.');
					sb.Append(index.Length > 0 ? "this[" + ParameterList(index, defaults: false, allowParams: false) + "]" : Names.Identifier(ip.Name)).Append("\n{\n");
					if (ip.GetMethod != null)
					{
						sb.Append("\tget => ").Append(Throw(display)).Append(";\n");
					}
					if (ip.SetMethod != null)
					{
						sb.Append("\tset => ").Append(Throw(display)).Append(";\n");
					}
					sb.Append("}\n");
					members.Add(new Member { Group = 7, Sort = key, Text = sb.ToString() });
				}
				foreach (EventInfo ie in i.GetEvents(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
				{
					string key = MemberKeys.Event(ie, iName);
					if (h != null && h.Members.Contains(key) || events.Any(e => e.Name == ie.Name))
					{
						continue;
					}
					string display = typeName + "." + iName + "." + ie.Name;
					members.Add(new Member
					{
						Group = 7,
						Sort = key,
						Text = "event " + Names.Render(ie.EventHandlerType) + " " + iRender + "." + Names.Identifier(ie.Name) + "\n{\n\tadd => " + Throw(display) + ";\n\tremove => " + Throw(display) + ";\n}\n",
					});
				}
			}
		}

		private static bool SameParameters(ParameterInfo[] a, ParameterInfo[] b)
		{
			if (a.Length != b.Length)
			{
				return false;
			}
			for (int i = 0; i < a.Length; i++)
			{
				if (a[i].ParameterType.ToString() != b[i].ParameterType.ToString())
				{
					return false;
				}
			}
			return true;
		}

		// ---- parameters ----

		private static string ParameterList(ParameterInfo[] ps, bool defaults, bool allowParams = true)
		{
			return string.Join(", ", ps.Select(p => Parameter(p, defaults, allowParams)));
		}

		private static string Parameter(ParameterInfo p, bool defaults, bool allowParams)
		{
			var sb = new StringBuilder();
			Type type = p.ParameterType;
			if (type.IsByRef)
			{
				sb.Append(MemberKeys.Direction(p));
			}
			else if (allowParams && p.GetCustomAttributesData().Any(a => a.AttributeType.FullName == "System.ParamArrayAttribute"))
			{
				sb.Append("params ");
			}
			sb.Append(Names.Render(type)).Append(' ').Append(Names.Identifier(string.IsNullOrEmpty(p.Name) ? "arg" + p.Position : p.Name));
			if (defaults && !type.IsByRef && p.HasDefaultValue)
			{
				sb.Append(" = ").Append(Names.Literal(p.RawDefaultValue, type));
			}
			return sb.ToString();
		}

		public string OmittedText() => string.Concat(omitted.Select(line => line + "\n"));
