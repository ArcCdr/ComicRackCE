using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Compat.Shared;
using Xunit;

namespace Compat.Drawing.Tests
{
	/// <summary>The load context of the drift guard, shared by the tests of one class (reading the reference assemblies takes a second).</summary>
	public sealed class DrawingSurfaceFixture : IDisposable
	{
		internal SurfaceFixture Surface { get; }

		public DrawingSurfaceFixture()
		{
			string reference = Path.GetDirectoryName(ReferencePack.Find());
			string omitted = Path.Combine(MacRoot.Find(), "cYo.Compat.Drawing", "Generated", "omitted.txt");
			Surface = new SurfaceFixture(reference, new[] { "System.Drawing.Common" }, new[] { typeof(System.Drawing.Bitmap).Assembly.Location }, omitted);
		}

		public void Dispose() => Surface.Dispose();
	}

	/// <summary>
	/// The stand-in must stay the surface of System.Drawing.Common: every visible type with the same kind, base type and interfaces, enums with identical names and values,
	/// and every public and protected member with the same signature, modifiers and parameter names (P4.7: generated by mac/tools/facade-gen, completed by hand where the shim implements something).
	/// The only public type that is not in the reference is cYo.Compat.Drawing.SkiaInterop.
	/// </summary>
	public class ShimSurfaceTests : IClassFixture<DrawingSurfaceFixture>
	{
		private readonly SurfaceFixture surface;

		public ShimSurfaceTests(DrawingSurfaceFixture fixture)
		{
			surface = fixture.Surface;
		}

		private static string Report(IEnumerable<string> lines, string title)
		{
			var list = lines.ToList();
			return list.Count == 0 ? "" : title + " (" + list.Count + "):\n  " + string.Join("\n  ", list.Take(40)) + (list.Count > 40 ? "\n  ..." : "");
		}

		[Fact]
		public void The_only_public_type_outside_the_reference_is_SkiaInterop()
		{
			var reference = new HashSet<string>(surface.ReferenceTypes.Select(t => t.FullName), StringComparer.Ordinal);
			string[] extra = typeof(System.Drawing.Bitmap).Assembly.GetExportedTypes().Where(t => !reference.Contains(t.FullName)).Select(t => t.FullName).ToArray();
			Assert.Equal(new[] { "cYo.Compat.Drawing.SkiaInterop" }, extra);
		}

		[Fact]
		public void The_reference_has_the_surface_the_generator_covers()
		{
			Assert.True(surface.ReferenceTypes.Count > 150, "only " + surface.ReferenceTypes.Count + " reference types");
			Assert.NotNull(surface.Facade("System.Drawing.Graphics"));
			Assert.NotNull(surface.Facade("System.Drawing.Printing.PrintDocument"));
		}

		[Fact]
		public void Every_visible_type_of_the_reference_is_declared()
		{
			string missing = Report(surface.ReferenceTypes.Where(t => surface.Facade(t.FullName) == null).Select(t => t.FullName), "types of the reference that the stand-in lacks");
			Assert.True(missing == "", missing);
		}

		[Fact]
		public void The_types_have_the_kind_base_type_interfaces_and_enum_values_of_the_reference()
		{
			var differences = new List<string>();
			foreach (Type reference in surface.ReferenceTypes)
			{
				Type facade = surface.Facade(reference.FullName);
				if (facade != null)
				{
					differences.AddRange(surface.ShapeDifferences(reference, facade).Select(d => reference.FullName + ": " + d));
				}
			}
			Assert.True(differences.Count == 0, Report(differences, "shape differences"));
		}

		[Fact]
		public void The_members_are_those_of_the_reference()
		{
			var differences = new List<string>();
			foreach (Type reference in surface.ReferenceTypes)
			{
				Type facade = surface.Facade(reference.FullName);
				if (facade == null)
				{
					continue;
				}
				var expected = new HashSet<string>(surface.Members(reference), StringComparer.Ordinal);
				var actual = new HashSet<string>(surface.Members(facade), StringComparer.Ordinal);
				differences.AddRange(expected.Except(actual).OrderBy(s => s, StringComparer.Ordinal).Select(s => reference.FullName + " lacks " + s));
				// An override that the shim adds (to release its own state) is not API surface: the reference has the virtual member on a base type.
				differences.AddRange(actual.Except(expected).Where(s => !s.StartsWith("method protected override ", StringComparison.Ordinal)).OrderBy(s => s, StringComparer.Ordinal).Select(s => reference.FullName + " has extra " + s));
			}
			Assert.True(differences.Count == 0, Report(differences, "member differences"));
		}
	}
}
