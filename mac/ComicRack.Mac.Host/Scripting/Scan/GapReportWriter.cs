using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace ComicRack.Mac.Host.Scripting.Scan
{
	/// <summary>Writes the gap report (P4.17) as Markdown (the file named by --markdown) and as JSON. No times, no machine paths: the same input gives the same text.</summary>
	public static class GapReportWriter
	{
		public static readonly string[] Statuses = { "real", "stub", "partial", "missing", "differs", "plugin", "python", "dynamic" };

		public static void WriteMarkdown(PluginGapReport report, TextWriter w, IReadOnlyDictionary<string, string> notes, string command)
		{
			w.WriteLine("# Plugin gap report");
			w.WriteLine();
			w.WriteLine("Generated by `" + command + "` (task P4.17). It lists, per plugin, every API the plugin reaches and what the macOS build has: the facades `System.Windows.Forms` and `System.Drawing.Common` (generated from the");
			w.WriteLine("reference assemblies, `real` = hand-written behaviour, `stub` = throws `NotSupportedException`), `System.Web.Extensions`, the Core (`ComicRack.Engine`, `ComicRack.Plugins`, `cYo.Common`), the .NET 10 runtime, the");
			w.WriteLine("Python 2.7 library and the files of the plugin. Nothing here is plugin specific code: the scan, the type index and the rules are generic (R11). The packages are untrusted downloads, read in memory by the scanner and");
			w.WriteLine("run only by the plugin host (the install and load probe). Regenerate after a task changes a facade: `mac/scripting/plugin-gap.sh`.");
			w.WriteLine();
			w.WriteLine("Reference surface: " + report.ReferenceSource + " (" + report.ReferenceTypes + " types). Facade, Core and runtime types are indexed from the assemblies of the program and of the .NET 10 runtime.");
			w.WriteLine();
			w.WriteLine("Status: `real` present and working; `stub` present, throws `NotSupportedException` at the use; `partial` some overloads or accessors are stubs (or, in the by-name table, the candidate types differ);");
			w.WriteLine("`missing` not there; `differs` there but behaves differently on macOS (see the note); `plugin` defined by the plugin itself; `python` a member of a Python built-in type; `dynamic` no known type has a member of that");
			w.WriteLine("name (plugin data or a dynamic attribute). Every row has exactly one status. Rows that need work (`stub`, `partial`, `missing`, `differs`) name the task that implements them in the Task column.");
			w.WriteLine();
			w.WriteLine("## Summary");
			w.WriteLine();
			w.WriteLine("| Plugin | Scripts | Assemblies | Native files | Tier | Rows | " + string.Join(" | ", Statuses) + " |");
			w.WriteLine("|---|---|---|---|---|---|" + string.Concat(Statuses.Select(_ => "---|")));
			foreach (PluginGap p in report.Plugins)
			{
				List<GapRow> all = p.AllRows.ToList();
				w.WriteLine("| " + Title(p) + " | " + p.PythonUnits + " | " + p.AssemblyUnits + " | " + p.NativeFiles + " | " + p.Tier + " | " + all.Count + " | " + string.Join(" | ", Statuses.Select(s => all.Count(r => r.Status == s))) + " |");
			}
			w.WriteLine();
			foreach (PluginGap p in report.Plugins)
			{
				WritePlugin(p, w, notes);
			}
		}

		private static string Title(PluginGap p) => p.Facts.Ini.TryGetValue("Name", out string n) && !string.IsNullOrEmpty(n) ? n + (p.Facts.Ini.TryGetValue("Version", out string v) ? " " + v : string.Empty) : p.Facts.Id;

		private static void WritePlugin(PluginGap p, TextWriter w, IReadOnlyDictionary<string, string> notes)
		{
			PluginFacts f = p.Facts;
			w.WriteLine("## " + Title(p));
			w.WriteLine();
			w.WriteLine("| | |");
			w.WriteLine("|---|---|");
			w.WriteLine("| Package | `" + f.PackageFile + "` (" + f.Size.ToString("N0", System.Globalization.CultureInfo.InvariantCulture) + " bytes) |");
			w.WriteLine("| SHA-256 | `" + f.Sha256 + "` |");
			if (f.Url != null)
			{
				w.WriteLine("| Source | " + f.Url + " |");
			}
			if (f.Licence != null)
			{
				w.WriteLine("| Licence | " + f.Licence + " (kept local: " + (f.Licence == "none stated" ? "the repository states no licence, so only scan results are committed" : "scan results only are committed") + ") |");
			}
			foreach (string key in new[] { "Author", "Description", "HelpLink" })
			{
				if (f.Ini.TryGetValue(key, out string v) && !string.IsNullOrEmpty(v))
				{
					w.WriteLine("| " + key + " | " + Cell(v) + " |");
				}
			}
			w.WriteLine("| Files scanned | " + p.Units + " (" + p.PythonUnits + " Python, " + p.AssemblyUnits + " .NET assemblies, " + p.NativeFiles + " native) |");
			w.WriteLine("| Tier | " + p.Tier + " |");
			w.WriteLine();

			w.WriteLine("### Hooks and commands the plugin registers");
			w.WriteLine();
			w.WriteLine("Hook names in the scripts: " + (p.Hooks.Count == 0 ? "none" : string.Join(", ", p.Hooks.Select(h => "`" + h + "`"))) + ".");
			w.WriteLine();
			w.WriteLine("| Command | Key | Hook | Enabled | File |");
			w.WriteLine("|---|---|---|---|---|");
			foreach (GapCommand c in f.Commands)
			{
				w.WriteLine("| " + Cell(c.Name) + " | " + Cell(c.Key ?? "") + " | " + Cell(c.Hook ?? "") + " | " + (c.Enabled ? "yes" : "no") + " | `" + c.File + "` |");
			}
			w.WriteLine();

			w.WriteLine("### Install and load in the plugin host");
			w.WriteLine();
			w.WriteLine("Installed through the `.crplugin` install path (`PluginPackages.InstallNow`); the top level of each script with commands is run, as the host does at the first use of a command.");
			w.WriteLine();
			w.WriteLine("| Script | Commands | Top level |");
			w.WriteLine("|---|---|---|");
			foreach (GapLoadCheck c in f.LoadChecks)
			{
				w.WriteLine("| `" + c.File + "` | " + c.Commands + " | " + (c.Ok ? "runs" : "fails: " + Cell(c.Message)) + " |");
			}
			w.WriteLine();

			if (notes != null && notes.TryGetValue(f.Id, out string text))
			{
				w.WriteLine(text.TrimEnd());
				w.WriteLine();
			}

			Table(w, "A. WinForms and GDI+ members (typed)", "Members of `System.Windows.Forms` and `System.Drawing` the scan could attribute to a type, by the type that declares them.", p.Surface, "Member", full: true);
			Table(w, "B. Member accesses on values of unknown type (by name)", "Python is dynamic: an access such as `x.Name` has no type. Each name is classified by the first group that has a member of that name: Python built-ins, the plugin's own definitions, the types the plugin uses, the Core, the imported .NET namespaces, the WinForms/GDI+ surface.", p.ByName, "Name", full: false);
			Table(w, "C. .NET 10 types and members", "System.*, Microsoft.* names the plugin imports or calls (namespaces are not rows).", p.Framework, "API", full: true);
			Table(w, "D. Core types and members", "`ComicRack.Engine`, `ComicRack.Plugins`, `cYo.Common` names the plugin imports or calls. The hosted objects (`ComicRack.App`, ...) appear in table B by name.", p.Core, "API", full: true);
			Table(w, "E. Python modules", "Top-level names of imported modules: a file of the plugin, a built-in module of IronPython, or the Python 2.7 library in `Lib`.", p.Modules, "Module", full: true);
			Table(w, "F. Referenced assemblies", "`clr.AddReference` lines and assembly references.", p.References, "Assembly", full: true);

			w.WriteLine("### G. Findings of the scanner");
			w.WriteLine();
			if (p.Findings.Count == 0)
			{
				w.WriteLine("None.");
			}
			else
			{
				w.WriteLine("| Severity | Kind | Symbol | Files | Task | Message |");
				w.WriteLine("|---|---|---|---|---|---|");
				foreach (GapFinding g in p.Findings)
				{
					w.WriteLine("| " + g.Severity + " | " + g.Kind + " | `" + Cell(g.Symbol) + "` | " + g.Units + " | " + (g.Task ?? "") + " | " + Cell(g.Message) + " |");
				}
			}
			w.WriteLine();
		}

		private static void Table(TextWriter w, string title, string intro, IReadOnlyList<GapRow> rows, string first, bool full)
		{
			w.WriteLine("### " + title);
			w.WriteLine();
			w.WriteLine(intro + " " + rows.Count + " rows" + (rows.Count == 0 ? "." : ": " + string.Join(", ", Statuses.Where(s => rows.Any(r => r.Status == s)).Select(s => rows.Count(r => r.Status == s) + " " + s)) + "."));
			w.WriteLine();
			if (rows.Count == 0)
			{
				return;
			}
			bool candidates = rows.Any(r => r.Candidates != null);
			// rows that need no work are listed in full in the JSON; the Markdown keeps them short: the rows that need work are always listed, the others up to a limit
			List<GapRow> shown = rows.Where(r => r.NeedsTask).Concat(rows.Where(r => !r.NeedsTask).Take(full ? 40 : 15)).ToList();
			w.WriteLine("| " + first + " | Uses | Files | Status | Source | Task | " + (candidates ? "Candidates | " : string.Empty) + "Note |");
			w.WriteLine("|---|---|---|---|---|---|" + (candidates ? "---|" : string.Empty) + "---|");
			foreach (GapRow r in shown.OrderByDescending(r => r.Uses).ThenBy(r => r.Name, StringComparer.Ordinal))
			{
				w.WriteLine("| `" + Cell(r.Name) + "` | " + r.Uses + " | " + r.Units + " | " + r.Status + " | " + (r.Source ?? "") + " | " + (r.Owner ?? "") + " | " + (candidates ? Cell(r.Candidates ?? "") + " | " : string.Empty) + Cell(r.Note ?? "") + " |");
			}
			int hidden = rows.Count - shown.Count;
			if (hidden > 0)
			{
				w.WriteLine();
				w.WriteLine(hidden + " more rows with a status that needs no work are in the JSON (`" + title.Substring(0, 1) + "`).");
			}
			w.WriteLine();
		}

		private static string Cell(string text) => (text ?? string.Empty).Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ");

		public static string ToJson(PluginGapReport report)
		{
			var options = new JsonWriterOptions { Indented = true };
			using var stream = new MemoryStream();
			using (var json = new Utf8JsonWriter(stream, options))
			{
				json.WriteStartObject();
				json.WriteNumber("schema", 1);
				json.WriteStartArray("plugins");
				foreach (PluginGap p in report.Plugins)
				{
					json.WriteStartObject();
					json.WriteString("id", p.Facts.Id);
					json.WriteString("sha256", p.Facts.Sha256);
					json.WriteString("tier", p.Tier);
					foreach ((string name, IReadOnlyList<GapRow> rows) in new (string, IReadOnlyList<GapRow>)[] { ("surface", p.Surface), ("byName", p.ByName), ("framework", p.Framework), ("core", p.Core), ("modules", p.Modules), ("references", p.References) })
					{
						json.WriteStartArray(name);
						foreach (GapRow r in rows)
						{
							json.WriteStartObject();
							json.WriteString("name", r.Name);
							json.WriteNumber("uses", r.Uses);
							json.WriteNumber("files", r.Units);
							json.WriteString("status", r.Status);
							json.WriteString("source", r.Source);
							if (r.Owner != null)
							{
								json.WriteString("task", r.Owner);
							}
							if (r.Note != null)
							{
								json.WriteString("note", r.Note);
							}
							json.WriteEndObject();
						}
						json.WriteEndArray();
					}
					json.WriteEndObject();
				}
				json.WriteEndArray();
				json.WriteEndObject();
			}
			return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
		}
	}
}
