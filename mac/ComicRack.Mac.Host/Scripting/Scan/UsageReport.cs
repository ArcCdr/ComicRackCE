using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;

namespace ComicRack.Mac.Host.Scripting.Scan
{
	/// <summary>What the usage report (<c>mac/scripting/compat-usage.md</c>) says about how it was made.</summary>
	public sealed class UsageReportOptions
	{
		/// <summary>The command lines that produced the report (shown in the first section).</summary>
		public IReadOnlyList<string> Commands { get; init; } = Array.Empty<string>();

		/// <summary>Sentences about the scanned corpus (what the inputs are, what was left out and why).</summary>
		public IReadOnlyList<string> Notes { get; init; } = Array.Empty<string>();

		/// <summary>Rows of the ranked member table.</summary>
		public int TopMembers { get; init; } = 300;

		/// <summary>Rows of the name only table of members on values of unknown type.</summary>
		public int TopUntyped { get; init; } = 100;
	}

	/// <summary>
	/// The ranked backlog of the Script UI Compatibility Layer as a Markdown document (P4.6b, MACOS_NATIVE_PATH.md section 5.9.9 step 4): tier counts of units and plugins, the plugins, the ranked types and
	/// members, what the scan could not type, the referenced assemblies and the Tier C findings. It only formats a <see cref="ScanReport"/>: equal reports give equal text (no times, no machine paths), and nothing in
	/// it is about single plugins beyond their names as the scan found them.
	/// </summary>
	public static class UsageReport
	{
		private static readonly int[] CoverageSteps = { 25, 50, 100, 150, 200, 300, 500, 1000 };

		public static void Write(ScanReport report, TextWriter w, UsageReportOptions options)
		{
			options ??= new UsageReportOptions();
			List<PluginRow> plugins = Plugins(report);

			w.WriteLine("# Script compatibility usage");
			w.WriteLine();
			w.WriteLine("Generated by `crcli script-scan --markdown` (P4.6b). Do not edit by hand: regenerate with `mac/scripting/scan-corpus.sh`. Only scan results are kept in the repository; the plugins themselves are downloaded into `mac/fixtures/plugins/` (git ignored) and are never run (`mac/scripting/corpus.md`).");
			w.WriteLine();
			w.WriteLine("This is the ranked implementation backlog of the Script UI Compatibility Layer (MACOS_NATIVE_PATH.md section 5.9): `type.member -> number of scripts that use it`. P4.7 generates the whole surface; P4.9 to P4.13 implement behaviour in the order of these tables.");
			w.WriteLine();

			w.WriteLine("## 1. How this was made");
			w.WriteLine();
			foreach (string c in options.Commands)
			{
				w.WriteLine("    " + c);
			}
			if (options.Commands.Count > 0)
			{
				w.WriteLine();
			}
			w.WriteLine("- Surface read from: " + CatalogName(report.Catalog) + " (" + report.Catalog.TypeCount.ToString(CultureInfo.InvariantCulture) + " types of `System.Windows.Forms*` and `System.Drawing*`)" + (report.Catalog.IsComplete ? "." : ", incomplete: names it lacks are not resolved."));
			foreach (string n in options.Notes)
			{
				w.WriteLine("- " + n);
			}
			w.WriteLine("- A *unit* is one script, assembly or HTML file; a *plugin* is the package it belongs to (a `.crplugin` file, a plugin folder, or a loose script). Scripts of the Python standard library that a plugin carries are units too (tier none); the plugin counts are the figures to read.");
			w.WriteLine("- Python is dynamic: an access on a value whose type the scan could not tell is counted in section 5, not in the member table. Assemblies are measured by member references of their metadata (a reference, not a call count).");
			w.WriteLine();

			w.WriteLine("## 2. Tiers");
			w.WriteLine();
			w.WriteLine("| Tier | Meaning | Units | Plugins |");
			w.WriteLine("|---|---|---:|---:|");
			TierRow(w, report, plugins, "A", "uses only Tier A types (must, v1): the common dialog and form controls and System.Drawing");
			TierRow(w, report, plugins, "B", "also uses a Tier B type (should): list and tree views, tool strips, data grids, rich text, colour and font dialogs, the web browser control");
			TierRow(w, report, plugins, "C", "has a finding that cannot run on macOS (Windows libraries, window procedures, the MSHTML document model, COM, registry): a clear error at run time");
			TierRow(w, report, plugins, "none", "no use of System.Windows.Forms or System.Drawing");
			TierRow(w, report, plugins, "?", "cannot be read (not Python 2 syntax, damaged assembly)");
			w.WriteLine();
			int ui = plugins.Count(p => p.Tier == "A" || p.Tier == "B");
			int uiUnits = report.Units.Count(u => u.Tier == "A" || u.Tier == "B");
			w.WriteLine("Plugins: " + plugins.Count + " (" + ui + " are Tier A or B and can run once the layer covers the tables below; " + plugins.Count(p => p.Tier == "C") + " are Tier C because some unit of them is, see section 7). Units: " + report.Units.Count + " (" + uiUnits + " Tier A or B).");
			w.WriteLine();
			w.WriteLine("A plugin has the highest tier of its units. A Tier C unit is not always something the plugin calls: a bundled third-party library that merely contains P/Invoke declarations is Tier C by the definition of the scan (section 7 lists the reasons).");
			w.WriteLine();

			w.WriteLine("## 3. Plugins");
			w.WriteLine();
			w.WriteLine("| Plugin | Tier | Units | Python | Assemblies | Forms and GDI+ types | Errors | Warnings |");
			w.WriteLine("|---|:-:|---:|---:|---:|---:|---:|---:|");
			foreach (PluginRow p in plugins.OrderBy(p => p.Name, StringComparer.OrdinalIgnoreCase).ThenBy(p => p.Name, StringComparer.Ordinal))
			{
				w.WriteLine("| " + Cell(p.Name) + " | " + p.Tier + " | " + p.Units.Count + " | " + p.Units.Count(u => u.Kind == "python") + " | " + p.Units.Count(u => u.Kind == "assembly") + " | " + p.Types + " | " + p.Errors + " | " + p.Warnings + " |");
			}
			w.WriteLine();

			w.WriteLine("## 4. Types ranked by scripts");
			w.WriteLine();
			w.WriteLine("Tier S = supporting type (enum, struct, delegate, event arguments). Rows: every type any unit uses.");
			w.WriteLine();
			w.WriteLine("| # | Type | Tier | Scripts | Plugins | Uses |");
			w.WriteLine("|---:|---|:-:|---:|---:|---:|");
			int rank = 0;
			foreach (TypeUsage t in report.Types)
			{
				rank++;
				w.WriteLine("| " + rank + " | " + Cell(t.Name) + (t.Known ? string.Empty : " (not in the catalog)") + " | " + t.Tier + " | " + t.Scripts + " | " + t.Packages + " | " + t.Uses + " |");
			}
			w.WriteLine();

			w.WriteLine("## 5. Members ranked by scripts");
			w.WriteLine();
			int shown = Math.Min(options.TopMembers, report.Members.Count);
			w.WriteLine("The first " + shown + " of " + report.Members.Count + " members (the full table is in the JSON of the same command). Members are reported against the type that declares them.");
			w.WriteLine();
			Coverage(w, report);
			w.WriteLine("| # | Type.member | Kind | Tier | Scripts | Plugins | Uses |");
			w.WriteLine("|---:|---|---|:-:|---:|---:|---:|");
			rank = 0;
			foreach (MemberUsage m in report.Members.Take(shown))
			{
				rank++;
				w.WriteLine("| " + rank + " | " + Cell(m.Key) + " | " + m.Kind + " | " + m.Tier + " | " + m.Scripts + " | " + m.Packages + " | " + m.Uses + " |");
			}
			w.WriteLine();

			w.WriteLine("## 6. Member names the scan could not type");
			w.WriteLine();
			int untyped = report.Units.Sum(u => u.Untyped);
			w.WriteLine("The scan found " + untyped + " accesses on values of unknown type (" + report.Units.Count(u => u.Untyped > 0) + " units). The table is the name only fallback ranking of those names that some type of the surface also has: " + report.UntypedMembers.Count + " names, the first " + Math.Min(options.TopUntyped, report.UntypedMembers.Count) + " shown. Implement a name from here when it also appears for a type in section 5, or when the owning type is obvious from the script.");
			w.WriteLine();
			w.WriteLine("| # | Member name | Scripts | Uses |");
			w.WriteLine("|---:|---|---:|---:|");
			rank = 0;
			foreach (UntypedUsage n in report.UntypedMembers.Take(options.TopUntyped))
			{
				rank++;
				w.WriteLine("| " + rank + " | " + Cell(n.Name) + " | " + n.Scripts + " | " + n.Uses + " |");
			}
			w.WriteLine();

			w.WriteLine("## 7. Findings: what cannot run, and what may misbehave");
			w.WriteLine();
			Findings(w, report);

			w.WriteLine("## 8. Referenced assemblies");
			w.WriteLine();
			w.WriteLine("Names that `clr.AddReference*` calls and assembly references give, by number of scripts. Kinds: forms, drawing, core (provided by the program), core-missing (a program assembly the macOS build does not have), framework, framework-only (.NET Framework assemblies that .NET 10 lacks), wpf, com, windows, bundled (a file of the same plugin), other.");
			w.WriteLine();
			w.WriteLine("| Assembly | Kind | Scripts |");
			w.WriteLine("|---|---|---:|");
			foreach (ReferenceUsage r in report.References)
			{
				w.WriteLine("| " + Cell(r.Name) + " | " + r.Kind + " | " + r.Scripts + " |");
			}
			w.WriteLine();
		}

		private static string CatalogName(ApiCatalog catalog)
		{
			string source = (catalog.Source ?? string.Empty).Replace('\\', '/');
			const string pack = "microsoft.windowsdesktop.app.ref/";
			int i = source.IndexOf(pack, StringComparison.OrdinalIgnoreCase);
			if (i >= 0)
			{
				string rest = source.Substring(i + pack.Length);
				int slash = rest.IndexOf('/');
				return "the reference assemblies of the Windows Desktop reference pack " + (slash > 0 ? rest.Substring(0, slash) : rest);
			}
			return source.Contains("facade", StringComparison.OrdinalIgnoreCase) ? "the facade assemblies of the macOS build" : "the reference assemblies given with --reference-pack";
		}

		private static string Cell(string text) => (text ?? string.Empty).Replace("|", "\\|").Replace("\n", " ");

		private sealed class PluginRow
		{
			public string Name;
			public string Tier = "none";
			public List<ScanUnit> Units = new List<ScanUnit>();
			public int Types;
			public int Errors;
			public int Warnings;
		}

		private static List<PluginRow> Plugins(ScanReport report)
		{
			var rows = new List<PluginRow>();
			foreach (IGrouping<string, ScanUnit> g in report.Units.GroupBy(u => u.Package ?? string.Empty, StringComparer.Ordinal))
			{
				var row = new PluginRow { Name = g.Key, Units = g.ToList() };
				string tier = "none";
				foreach (ScanUnit u in row.Units)
				{
					if (u.Tier != "?" && ApiTiers.Rank(u.Tier) > ApiTiers.Rank(tier))
					{
						tier = u.Tier;
					}
					row.Errors += u.Findings.Count(f => f.Severity == "error");
					row.Warnings += u.Findings.Count(f => f.Severity == "warning");
				}
				if (tier == "none" && row.Units.All(u => u.Tier == "?"))
				{
					tier = "?";
				}
				row.Tier = tier;
				row.Types = row.Units.SelectMany(u => u.Types.Keys).Distinct(StringComparer.Ordinal).Count();
				rows.Add(row);
			}
			return rows;
		}

		private static void TierRow(TextWriter w, ScanReport report, List<PluginRow> plugins, string tier, string meaning)
		{
			w.WriteLine("| " + tier + " | " + meaning + " | " + report.Units.Count(u => u.Tier == tier) + " | " + plugins.Count(p => p.Tier == tier) + " |");
		}

		/// <summary>How many Tier A and B units run completely when the first N ranked members work (types and members the scan could type; an access it could not type is not counted).</summary>
		private static void Coverage(TextWriter w, ScanReport report)
		{
			List<ScanUnit> candidates = report.Units.Where(u => u.Tier == "A" || u.Tier == "B").ToList();
			if (candidates.Count == 0)
			{
				return;
			}
			w.WriteLine("Coverage: Tier A and B units (" + candidates.Count + ") whose typed members are all among the first N ranked members.");
			w.WriteLine();
			w.WriteLine("| First N members | Units covered | Share |");
			w.WriteLine("|---:|---:|---:|");
			var steps = CoverageSteps.Where(n => n < report.Members.Count).ToList();
			steps.Add(report.Members.Count);
			foreach (int n in steps.Distinct())
			{
				var top = new HashSet<string>(report.Members.Take(n).Select(m => m.Type + "::" + m.Member), StringComparer.Ordinal);
				int covered = candidates.Count(u => u.Members.Keys.All(top.Contains));
				w.WriteLine("| " + (n == report.Members.Count ? "all " + n : n.ToString(CultureInfo.InvariantCulture)) + " | " + covered + " | " + (100.0 * covered / candidates.Count).ToString("0.0", CultureInfo.InvariantCulture) + "% |");
			}
			w.WriteLine();
		}

		private static void Findings(TextWriter w, ScanReport report)
		{
			var errors = new List<(ScanUnit unit, ScanFinding finding)>();
			var warnings = new List<(ScanUnit unit, ScanFinding finding)>();
			foreach (ScanUnit u in report.Units)
			{
				foreach (ScanFinding f in u.Findings)
				{
					(f.Severity == "error" ? errors : warnings).Add((u, f));
				}
			}
			w.WriteLine("**Errors (Tier C): " + errors.Count + " in " + errors.Select(e => e.unit.Path).Distinct().Count() + " units of " + errors.Select(e => e.unit.Package).Distinct().Count() + " plugins.** Each is the sentence of the compatibility report: \"Uses Windows-only API `x`; this script cannot run on macOS\".");
			w.WriteLine();
			if (errors.Count > 0)
			{
				w.WriteLine("| Kind | Findings | Units | Plugins |");
				w.WriteLine("|---|---:|---:|---:|");
				foreach (IGrouping<string, (ScanUnit unit, ScanFinding finding)> g in errors.GroupBy(e => e.finding.Kind, StringComparer.Ordinal).OrderByDescending(g => g.Select(e => e.unit.Package).Distinct().Count()).ThenByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal))
				{
					w.WriteLine("| " + g.Key + " | " + g.Count() + " | " + g.Select(e => e.unit.Path).Distinct().Count() + " | " + g.Select(e => e.unit.Package).Distinct().Count() + " |");
				}
				w.WriteLine();
				w.WriteLine("| Plugin | Unit | Symbols |");
				w.WriteLine("|---|---|---|");
				foreach (IGrouping<ScanUnit, (ScanUnit unit, ScanFinding finding)> g in errors.GroupBy(e => e.unit).OrderBy(g => g.Key.Package, StringComparer.Ordinal).ThenBy(g => g.Key.Path, StringComparer.Ordinal))
				{
					List<string> symbols = g.Select(e => e.finding.Symbol).Distinct(StringComparer.Ordinal).OrderBy(s => s, StringComparer.Ordinal).ToList();
					string text = string.Join(", ", symbols.Take(8).Select(s => "`" + s + "`")) + (symbols.Count > 8 ? " and " + (symbols.Count - 8) + " more" : string.Empty);
					w.WriteLine("| " + Cell(g.Key.Package) + " | " + Cell(g.Key.Path.Substring(g.Key.Path.LastIndexOf('/') + 1)) + " | " + text + " |");
				}
				w.WriteLine();
			}
			w.WriteLine("**Warnings: " + warnings.Count + " in " + warnings.Select(e => e.unit.Path).Distinct().Count() + " units of " + warnings.Select(e => e.unit.Package).Distinct().Count() + " plugins.** These may misbehave on macOS but do not stop the plugin.");
			w.WriteLine();
			if (warnings.Count > 0)
			{
				w.WriteLine("| Kind | Findings | Units | Plugins |");
				w.WriteLine("|---|---:|---:|---:|");
				foreach (IGrouping<string, (ScanUnit unit, ScanFinding finding)> g in warnings.GroupBy(e => e.finding.Kind, StringComparer.Ordinal).OrderByDescending(g => g.Select(e => e.unit.Package).Distinct().Count()).ThenByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal))
				{
					w.WriteLine("| " + g.Key + " | " + g.Count() + " | " + g.Select(e => e.unit.Path).Distinct().Count() + " | " + g.Select(e => e.unit.Package).Distinct().Count() + " |");
				}
				w.WriteLine();
			}
			List<ScanUnit> unreadable = report.Units.Where(u => !u.Parsed).ToList();
			if (unreadable.Count > 0)
			{
				w.WriteLine("**Unreadable units: " + unreadable.Count + ".** The IronPython parser reads Python 2 only; these are not valid Python 2 or not valid assemblies.");
				w.WriteLine();
				w.WriteLine("| Plugin | Unit | Reason |");
				w.WriteLine("|---|---|---|");
				foreach (ScanUnit u in unreadable.OrderBy(u => u.Path, StringComparer.Ordinal))
				{
					w.WriteLine("| " + Cell(u.Package) + " | " + Cell(u.Path.Substring(u.Path.LastIndexOf('/') + 1)) + " | " + Cell(u.Error) + " |");
				}
				w.WriteLine();
			}
		}
	}
}
